#include <iostream>
using namespace std;

int main() {
   int x = 0; // Membuat variabel x dan memberikan nilai 0

// Pengecekan pertama: Apakah x bernilai tepat 0?
if (x == 0) { 
    // Karena x adalah 0, kondisi ini BENAR (true)
    cout << "x adalah 0" << endl; 
}

// Pengecekan kedua: Apakah x lebih besar dari atau sama dengan 0?
if (x >= 0) { 
    // Karena 0 sama dengan 0, kondisi ini juga BENAR (true)
    cout << "x adalah non-negatif" << endl; 
}
}

// c. x adalah 0
// x adalah non-negatif
