#include <iostream> // Header untuk proses input dan output (seperti menampilkan teks)

using namespace std; // Agar tidak perlu menulis 'std::' di depan fungsi seperti cout atau endl

int main() { // Fungsi utama tempat program mulai dijalankan
    
    // Mendeklarasikan variabel x dan menjumlahkan angka 1 sampai 4 (hasilnya 10)
    int x = 1 + 2 + 3 + 4; 

    // Mengecek apakah nilai di dalam variabel x sama dengan 10
    if (x == 10) { 
        // Jika benar (true), maka cetak teks di bawah ini ke layar
        cout << "nilai x adalah 10" << endl; 
    }

    return 0; // Menandakan bahwa program telah berakhir dengan sukses
}

// a. nilai x adalah 10
